"""Render the no-checkout workflow from the reviewable canonical collector."""
import hashlib
import json
import ast
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent


def render(source):
    digest = hashlib.sha256(source).hexdigest()
    tree=ast.parse(source)
    keys=ast.literal_eval(next(n.value for n in tree.body if isinstance(n,ast.Assign) and isinstance(n.targets[0],ast.Name) and n.targets[0].id=='KEYS'))
    if not all(re.fullmatch(r'[A-Za-z][A-Za-z0-9_]*', key) for key in keys):raise ValueError('Unsafe environment key')
    launch='/usr/bin/env -i PATH=/usr/sbin:/usr/bin:/sbin:/bin LANG=C LC_ALL=C \\\n'
    launch+=''.join(key+'="${'+key+'-}" \\\n' for key in keys)
    launch+="/usr/bin/python3 -I -S -B - <<'PY'"
    bootstrap = "\n".join([
        launch, "import hashlib",
        "source = " + json.dumps(source.decode()), "expected = " + repr(digest),
        "if hashlib.sha256(source.encode()).hexdigest() != expected: raise SystemExit('Collector source mismatch')",
        "exec(compile(source, '<reviewed-host-inventory>', 'exec'), {'__name__': '__main__', 'SOURCE_SHA256': expected})", "PY"])
    header = '''# Generated by ops/cloud-audit/host-inventory/render_workflow.py.
# Proposal only. Publication/dispatch require separate explicit approval.
name: Faith host inventory proposal

on:
  workflow_dispatch:
    inputs:
      probe_sha:
        description: Independently approved full immutable probe commit; must equal selected ref
        type: string
        required: true
      storage_available:
        description: Owner confirms this artifact fits existing storage; no paid usage authorized
        type: boolean
        default: false
        required: true

permissions: {}

concurrency:
  group: faith-host-inventory-${{ github.repository_id }}
  cancel-in-progress: false

jobs:
  inventory:
    if: >-
      github.event_name == 'workflow_dispatch' &&
      github.repository == 'II-ricky-bobby-II/Faith-on-the-Frontlines' &&
      github.repository_id == '1355135878' &&
      github.actor == 'II-ricky-bobby-II' && github.actor_id == '116130409' &&
      github.triggering_actor == 'II-ricky-bobby-II' &&
      github.ref == 'refs/heads/chore/faith-host-inventory-offline' &&
      github.run_attempt == '1' && github.sha == inputs.probe_sha &&
      toJSON(github.event.repository.private) == 'false' && inputs.storage_available == true
    runs-on: ubuntu-22.04
    timeout-minutes: 5
    permissions: {}
    steps:
      - name: Collect only reviewed read-only host facts
        timeout-minutes: 3
        shell: bash --noprofile --norc -eo pipefail {0}
        env:
          FOTF_APPROVED_SHA: ${{ inputs.probe_sha }}
          FOTF_REPOSITORY_PUBLIC: ${{ toJSON(github.event.repository.private) == 'false' }}
          FOTF_STORAGE_CONFIRMED: ${{ inputs.storage_available }}
        run: |
'''
    body = "".join("          " + line + "\n" for line in bootstrap.splitlines())
    footer = '''      - name: Retain bounded inventory evidence even on refusal
        if: ${{ always() }}
        timeout-minutes: 1
        uses: actions/upload-artifact@ea165f8d65b6e75b540449e92b4886f43607fa02
        with:
          name: fotf-host-inventory-${{ github.run_id }}-${{ github.run_attempt }}
          path: |
            host-inventory-evidence/inventory.json
            host-inventory-evidence/manifest.json
          retention-days: 90
          if-no-files-found: error
          include-hidden-files: false
          overwrite: false
'''
    return (header + body + footer).encode()


if __name__ == "__main__":
    repository = ROOT.parents[2]
    (repository / ".github/workflows/cloud-audit.yml").write_bytes(render((ROOT / "collector.py").read_bytes()))
